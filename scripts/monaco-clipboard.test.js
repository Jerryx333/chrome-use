import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'
import vm from 'node:vm'

const source = readFileSync(new URL('../cli/src/native/monaco_clipboard.js', import.meta.url), 'utf8')
const item = values => ({ types: Object.keys(values), async getType(type) { return new Blob([values[type]]) } })
function fixture({ denyRead = false, denyStage = false, denyRestore = false, throwFocus = false, deferredStage = false } = {}) {
  let contents = [item({ 'text/plain': 'before', 'text/html': '<b>before</b>' })]
  let restores = 0, stages = 0, releaseStage
  const listeners = new Map(), timers = new Map()
  let nextTimer = 0
  const clipboard = {
    async read() { if (denyRead) throw Error('read denied'); return contents },
    async write(items) { restores++; if (denyRestore) throw Error('restore denied'); contents = items },
    async writeText(text) {
      stages++
      if (denyStage) throw Error('stage denied')
      if (deferredStage) await new Promise(resolve => { releaseStage = resolve })
      contents = [item({ 'text/plain': text })]
    },
  }
  const doc = {
    defaultView: { navigator: { clipboard } },
    addEventListener(type, fn) { listeners.set(type, fn) },
    removeEventListener(type, fn) { if (listeners.get(type) === fn) listeners.delete(type) },
  }
  const input = { ownerDocument: doc, focus() { if (throwFocus) throw Error('focus failed') } }
  const root = { querySelector() { return input } }
  const anchor = { closest() { return root } }
  const beforeKeys = Reflect.ownKeys(anchor)
  const tx = vm.runInNewContext(`(${source})`, {
    TextEncoder, Uint8Array, queueMicrotask,
    setTimeout(fn, delay) { const id = ++nextTimer; timers.set(id, { fn, delay }); return id },
    clearTimeout(id) { timers.delete(id) },
  }).call(anchor)
  return {
    tx, listeners, timers, anchor, beforeKeys,
    get restores() { return restores }, get stages() { return stages },
    async contents() { return Promise.all(contents.map(async entry => Object.fromEntries(await Promise.all(entry.types.map(async type => [type, await (await entry.getType(type)).text()]))))) },
    change(values) { contents = [item(values)] },
    release() { releaseStage() },
    async event(type, values, { trusted = true, prevented = true, target = input } = {}) {
      // Fixture trust is supplied by the test, not generated by a real browser.
      listeners.get(type)?.({ isTrusted: trusted, defaultPrevented: prevented, composedPath: () => [target, doc],
        clipboardData: { types: Object.keys(values), getData: type => values[type] || '' } })
      await Promise.resolve()
    },
  }
}
test('private fill transaction restores all formats and stops listeners idempotently', async () => {
  const f = fixture()
  assert.equal((await f.tx.start('replacement')).ok, true)
  assert.deepEqual(Reflect.ownKeys(f.anchor), f.beforeKeys)
  await f.event('paste', {})
  assert.equal(f.tx.check('paste').trusted, true)
  await f.event('copy', { 'text/plain': 'replacement' })
  assert.equal(f.tx.check('copy').text, 'replacement')
  assert.equal((await f.tx.finish()).ok, true)
  await f.tx.finish()
  assert.equal(f.restores, 1)
  assert.equal(f.listeners.size, 0)
  assert.deepEqual(await f.contents(), [{ 'text/plain': 'before', 'text/html': '<b>before</b>' }])
})
test('read transaction verifies copied formats before restoration', async () => {
  const f = fixture()
  await f.tx.start(null)
  assert.equal(f.stages, 0)
  f.change({ 'text/plain': 'editor', 'text/html': '<i>editor</i>' })
  await f.event('copy', { 'text/plain': 'editor', 'text/html': '<i>editor</i>' })
  assert.equal((await f.tx.finish()).ok, true)
  assert.equal(f.listeners.size, 0)
})
test('focus exception after staging still restores and removes listeners', async () => {
  const f = fixture({ throwFocus: true })
  assert.match((await f.tx.start('new')).error, /focus failed/)
  assert.equal((await f.tx.finish()).ok, true)
  assert.equal(f.listeners.size, 0)
  assert.equal(f.restores, 1)
})
test('denied backup never stages and denied staging does not overwrite original', async () => {
  for (const options of [{ denyRead: true }, { denyStage: true }]) {
    const f = fixture(options)
    assert.equal((await f.tx.start('new')).ok, false)
    await f.tx.finish()
    assert.equal(f.restores, 0)
    assert.equal(f.listeners.size, 0)
    assert.deepEqual(Reflect.ownKeys(f.anchor), f.beforeKeys)
    if (options.denyRead) assert.equal(f.stages, 0)
  }
})
test('preserves newer text or formats, refusing uncertain ownership', async () => {
  for (const values of [{ 'text/plain': 'newer' }, { 'text/plain': 'staged', 'text/html': 'newer html' }]) {
    const f = fixture()
    await f.tx.start('staged')
    f.change(values)
    assert.match((await f.tx.finish()).error, /ownership is uncertain/)
    assert.deepEqual(await f.contents(), [values])
    assert.equal(f.restores, 0)
  }
})
test('untrusted and wrong-target copy cannot satisfy readback verification', async () => {
  const f = fixture()
  await f.tx.start(null)
  await f.event('copy', { 'text/plain': 'forged' }, { trusted: false })
  await f.event('copy', { 'text/plain': 'other' }, { target: {} })
  assert.equal(f.tx.check('copy'), null)
  await f.tx.finish()
})
test('failed full restoration has no destructive text-only fallback', async () => {
  const f = fixture({ denyRestore: true })
  await f.tx.start('staged')
  assert.match((await f.tx.finish()).error, /restore denied/)
  assert.equal(f.stages, 1)
  assert.equal(f.listeners.size, 0)
})
test('lease expiry during pending staging waits for it before restoration', async () => {
  const f = fixture({ deferredStage: true })
  const started = f.tx.start('staged')
  // Let asynchronous backup materialization reach writeText.
  for (let i = 0; i < 30 && !f.stages; i++) await new Promise(resolve => setImmediate(resolve))
  assert.equal(f.stages, 1)
  const timer = [...f.timers.values()].find(t => t.delay === 60000)
  timer.fn()
  assert.equal(f.listeners.size, 0)
  f.release()
  assert.match((await started).error, /expired/)
  assert.equal((await f.tx.finish()).ok, true)
  assert.equal(f.restores, 1)
})
